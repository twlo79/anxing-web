"""
安幸上工 品牌記號 —— 各尺寸圖檔產生器。

執行:  python3 scripts/gen-icons.py

============================================================
【★★★ Apple 的三條硬性規範】（2026-08-29 查 HIG 後修正）

  ① PNG **不能有圓角** —— 圓角由系統切。烘進圖裡會被再切一次,
     邊緣露出一圈底色。
  ② **不能透明**，必須不透明實底。
  ③ 1024×1024 要跟 **29×29** 是同一張圖 —— 最小尺寸認得出來是門檻。

============================================================
【★★★ 記號是「牆上開一個拱洞」，不是一扇門】（2026-08-31 定案）

  來回了四輪才走到這裡,四種都被否掉過:

  | 版本 | 為什麼不行 |
  |---|---|
  | 描邊的門 | 兩條邊縮到 29px 會黏成一團 |
  | 填滿的門 | 「我想設計的像積木」—— 是平的,沒有厚度 |
  | 積木方塊 ＋ 門 | 「我以為是一扇門 但有厚度」—— 門開在方塊上,不是門本身有厚度 |
  | 門板整片複製再位移 | 「你只是兩個疊一起」—— 那是兩扇門,不是一扇厚門 |

  ★★ 最後的參考是一張**拱洞嵌在牆上**的照片:厚度來自
    **看得到洞的內壁**（reveal）,而不是把形狀複製一份挪開。

  ★★★ 所以只有三個面:

    牆（最亮） · 內壁（中間） · 洞裡（最暗）

    內壁是「近端的洞」與「遠端的洞」之間的那一條帶子,
    只出現在**看得到的那一側**（這裡是左邊與上緣）。
    整片複製會讓兩邊都出現 —— 那就是被否掉的那一版。

============================================================
【設計決定】

  底部    洞的底**貼齊畫布下緣** —— 留一截牆在下面會變成窗戶
  厚度    位移 40／512 ≈ 2.5／32。使用者試過 6～7（太厚,像兩片門）
          與 1.5（16px 看不到），2.5 是「剛好還讀得到一條邊」
  洞色    **全站主色的深藍**,不是紅木 —— 紅木在介面裡沒有出現過,
          圖示跟介面連不起來
  內壁    主色**調亮**,不是「深藍加白」。混白會偏灰,那條帶子會髒
  對比    參考圖是同色系微差,很好看但**16px 會整團糊掉** ——
          所以三階的明度差刻意拉開

★★ 為什麼是腳本:同一個記號要出八個檔,手工改一次要重畫八次,
   而漏掉一個沒有人會發現 —— 那個尺寸只在某台裝置上出現。
"""
from PIL import Image, ImageDraw, ImageChops

SS = 4                      # 超取樣（PIL 沒有反鋸齒）
C  = 512                    # 設計畫布

# ══════════════════════════════════════════════════════════
# 【顏色】牆最亮 · 內壁中間 · 洞裡最暗
#
# ★★ 洞用**全站主色的深藍**（`mor` 色盤的 surf-deep 那一階）——
#   圖示跟介面才連得起來。舊版是紅木門，而紅木在介面裡沒有出現過。
#
# ★ 內壁不是「深藍加白」，是**主色調亮**（同一個色相往上提明度）。
#   直接混白會偏灰,那條帶子會看起來髒。
# ══════════════════════════════════════════════════════════
WALL_TOP, WALL_BOT = (243, 238, 227), (232, 224, 206)   # 米牆,上淺下深
HOLE_TOP, HOLE_BOT = (0x35, 0x59, 0x77), (0x1C, 0x33, 0x48)  # 洞:深藍,越裡面越暗
REVEAL             = (0x6E, 0x8C, 0xA8)                 # 內壁:主色調亮

# ── 幾何（512 座標系）──────────────────────────────
#
# ★ 洞的底部**貼齊畫布下緣**（BOT = C）—— 拱洞是「開在牆上的門」,
#   不是浮在牆中央的一個形狀。留一截牆在下面會變成窗戶。
LX, RX = 144, 368           # 洞的左右
CY, R  = 240, 112           # 拱心 y、半徑
BOT    = C                  # 洞的底＝畫布底

# ★★ 內壁的位移 = 視角。往右下 = 站在洞的左前方,看得到**左側**內壁。
#   位移量就是牆的厚度。40／512 ≈ 2.5／32,是使用者定的那一階。
DX, DY = 40, 30


def _vgrad(size, top, bot):
    im = Image.new('RGB', (1, size), top)
    px = im.load()
    for y in range(size):
        t = y / max(1, size - 1)
        px[0, y] = tuple(round(top[i] + (bot[i] - top[i]) * t) for i in range(3))
    return im.resize((size, size))


def _arch_mask(S, X, dx=0.0, dy=0.0):
    """拱形（上半圓 ＋ 下方矩形）的遮罩。dx/dy 是整體位移（512 座標系）。"""
    m = Image.new('L', (S, S), 0)
    d = ImageDraw.Draw(m)
    d.pieslice([X(LX + dx), X(CY - R + dy), X(RX + dx), X(CY + R + dy)], 180, 360, fill=255)
    d.rectangle([X(LX + dx), X(CY + dy), X(RX + dx), X(BOT + dy)], fill=255)
    return m


def draw(size, *, pad=0.0):
    """pad = 記號再往內縮的比例（maskable 用）。"""
    S = size * SS
    k = (S / C) * (1 - pad * 2)
    off = S * pad
    X = lambda v: off + v * k

    # ① 牆
    im = _vgrad(S, WALL_TOP, WALL_BOT)

    # ② 近端的洞（整個挖掉，先填內壁的顏色）
    near = _arch_mask(S, X)
    im = Image.composite(Image.new('RGB', (S, S), REVEAL), im, near)

    # ③ 遠端的洞（往右下位移）填暗色。
    #    ★★ 要跟 near 取**交集** —— 不然位移出去的部分會蓋到牆上,
    #    那就變成「牆上多一塊深藍」而不是「洞裡看到深處」。
    far = _arch_mask(S, X, DX, DY)
    inner = ImageChops.multiply(near, far)
    im = Image.composite(_vgrad(S, HOLE_TOP, HOLE_BOT), im, inner)

    return im.resize((size, size), Image.LANCZOS)


OUT = 'public/icons/'
JOBS = [
    # ★ 全部**滿版、不透明、無圓角** —— 圓角交給系統
    ('icon-512.png',          512, 0.0),
    ('icon-192.png',          192, 0.0),
    ('apple-touch-icon.png',  180, 0.0),
    ('logo-250.png',          250, 0.0),
    # ★ maskable:Android 會裁成圓形,記號縮進中央安全區
    ('icon-maskable-512.png', 512, 0.13),
    ('icon-maskable-192.png', 192, 0.13),
    # ★★ 小尺寸不用換畫法 —— 三個色階都是大面積,縮小不會黏
    ('favicon-32.png',         32, 0.0),
    ('favicon-16.png',         16, 0.0),
]
for name, size, pad in JOBS:
    draw(size, pad=pad).save(OUT + name)
    print('✓', name, f'{size}px', f'pad={pad}')
