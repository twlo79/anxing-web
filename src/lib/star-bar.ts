/**
 * 星等分布長條的配色（2026-08-28）。
 *
 * ============================================================
 * 【原本錯在哪】
 *
 * 五個顏色寫死在**三個地方**，三次抄同一組字串:
 *
 *     ['bg-amber-400','bg-orange-500','bg-red-500','bg-purple-500','bg-gray-900']
 *
 * 這組色是照白底挑的,但其中一處畫在**深藍卡**上（評價頁的總覽）。
 * 量出來對軌道的對比:
 *
 *   | 星等 | 色 | 對比 |
 *   |---|---|---|
 *   | 5 | amber-400  | 2.58 ✗ |
 *   | 4 | orange-500 | 2.14 ✗ |
 *   | 3 | red-500    | 1.62 ✗ |
 *   | 2 | purple-500 | 1.84 ✗ |
 *   | 1 | gray-900   | 1.43 ✗（深色印在深藍上,讀起來像一個洞不像一條 bar）|
 *
 * **五條全部不到門檻。** 而畫面不會說話 —— 它只是有點糊,
 * 每個人都以為是自己的螢幕。
 *
 *
 * ============================================================
 * 【★★ 非文字元件的門檻是 3:1，不是 4.5:1】
 *
 * 4.5:1 是**小字**的標準（WCAG 1.4.3）。長條、圖示、輸入框邊線這類
 * 「不是字但要看得出來」的東西走 1.4.11，門檻 3:1。
 *
 * 拿 4.5 去要求長條會逼出過深的顏色,反而讓卡片變髒。
 *
 *
 * ============================================================
 * 【★★ 比的對象是「軌道」，不是卡片背景】
 *
 * 軌道就在 bar 旁邊而且**緊貼著** —— 眼睛判斷「這條有多長」靠的是
 * bar 與軌道的分界,不是 bar 與卡片的分界。
 * 拿卡片底來算會高估,而高估的方向是「以為過了」。
 *
 * ★ 卡片是漸層（上淺下深），而五列各自坐在不同深淺的底上 ——
 *   所以每一條是拿**它自己那一列的高度**去算（見 `ROW_Y` 與 `deepAt`）,
 *   不是全部拿卡片中間。拿同一個底算五條的話，最上面那條會被高估。
 *
 *
 * ============================================================
 * 【★★ 使用者最後拍板的規則】（原話）
 *
 *   「5 星到 1 星越來越暗
 *     5 星 > 黃 / 4 星 > 橙 / 3 星 > 紅 / 2 星 > 紅紫 / 1 星 > 深紫藍
 *     下面一樣搭配，然後幫我配的與背景藍色和諧」
 *
 * ★ 這是一條**色相環上的散步**:44° → 29° → 9° → 337° → 281°。
 *   一路往回走，最後停在紫藍 —— 而卡片背景 `#3A5F86` 是 **211°**。
 *   1 星離背景只剩 70°，所以整條色帶是「從最遠走回家」。
 *   那就是「和背景和諧」的具體意思:終點跟底色是同一家人。
 *
 * ★★ 亮度**嚴格遞減**:64% → 42% → 28% → 23% → 21%。
 *   「越來越暗」不是感覺，是量出來的 —— 有一條測試釘著它。
 *
 * ★★★ 但**不能真的暗到看不見**,那正是舊版 1 星 `gray-900` 的下場。
 *   所以遞減有地板:每一條對它自己那一列的軌道都要 ≥ 3:1。
 *   最低的 1 星是 3.23:1 —— 貼著地板，但站在地板上。
 *
 *
 * ============================================================
 * 【★ 我在這件事上被修正了五次，值得寫下來】
 *
 *   ① 第一版把五色換成暖色階 →「原本比較好，小調色調就好」
 *   ② 「主要是 4 星到 1 星」   → 5 星別動
 *   ③ 「淡一些」               → 提明度
 *   ④ 「飽和度低一些」         → 降飽和
 *   ⑤ 最後才講出真正要的:一條由亮到暗的色相帶
 *   ⑥ 「5 星黃色鮮豔點」       → 5 星飽和度拉滿（S 92% → 100%）
 *
 * ★★ ① 的教訓是**我把「配色不搭」讀成了「重新配色」** ——
 *   一看到問題就重做整塊，連原本對的東西（5 星的金色）一起丟掉。
 *   ②③④ 每一次都是在把我拉回原地。
 *
 * ★ ⑥ 也說明了一件事:整條色帶不必平均。5 星佔 92% 的資料，
 *   它就該是最亮最鮮的那一條 —— 其餘四條收斂，讓它站出來。
 */

/** 星等由高到低:5、4、3、2、1。 */
