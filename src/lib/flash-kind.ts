/**
 * 一句頁面訊息是「錯誤」還是「成功／提示」—— 決定它會不會自己消失。
 *
 * ============================================================
 * 【★★★ 為什麼靠內容判斷，不多一個參數】
 *
 * 全站 `flash()` 有近 400 個呼叫點，其中一半是錯誤。改成 `flash(t, true)`
 * 要動一百多處，**漏一處就又變成一句綠色的、2.5 秒消失的錯誤** ——
 * 而漏掉的那一處不會有任何東西叫（shortterm 頁 2026-08 就是這樣決定的）。
 *
 * 現有的錯誤訊息幾乎都寫成「…失敗:」「無法…」「不能…」，抓得住。
 *
 * ★ 誤判的代價不對稱，所以規則寬一點：
 *   · 把提示誤判成錯誤 → 那句話多留一會、要按一下才消失（小麻煩）
 *   · 把錯誤誤判成提示 → 2.5 秒消失，使用者以為按了沒反應（半年那次房務支出）
 *
 * 【為什麼寫在 .ts】規則只有一份，而且要有測試 —— 它管的是「錯誤看不看得到」。
 */

const ERROR_WORDS =
  /失敗|錯誤|不能|無法|不可以|不到|沒寫|沒存|不夠|不對|超過|已存在|重複|請先|請填|請選|請輸入|可能是權限|多半是|⚠|❌|逾時|拒絕|沒有權限|一列都沒/;

/** 這句話是錯誤嗎 */
export function looksLikeError(t: string | null | undefined): boolean {
  return !!t && ERROR_WORDS.test(t);
}
