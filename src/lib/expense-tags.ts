/**
 * 支出標籤（`expenses.tags`）的唯一出處。
 *
 * ============================================================
 * 【為什麼要有這個檔】
 *
 * 這個字串**存進資料庫**，而讀它的地方有六個:
 *
 *   1. 排班統計產生支出時寫入        `stats-tab.tsx`
 *   2. 支出頁表格的 chip             `expenses/page.tsx`
 *   3. 手機版卡片的 chip             同上
 *   4. 抽屜裡的 chip                 同上
 *   5. 「非實支」開關的 PostgREST 查詢 同上（`.not('tags','cs','{…}')`）
 *   6. migration 的 `tags @> array[…]`
 *
 * ★★★ 六個地方各寫一次字串的話，改名時漏掉任何一個都**不會報錯** ——
 *   寫入端改了、篩選端沒改，症狀是「開關打開之後那幾十筆還在」，
 *   而畫面上看起來完全正常（CLAUDE.md:「同一條規則在三個地方各寫一次」）。
 *
 * ★ SQL 那一邊抄不到這裡，所以 migration 裡要**明寫**這個字串，
 *   並且在檔頭註明它跟這一支同步。
 *
 * ============================================================
 * 【2026-09-03 從「房務」改成「非實支」】（使用者指定）
 *
 * 舊的標籤叫「房務」，講的是**這筆錢從哪來**。
 * 新的叫「非實支」，講的是**這筆錢的性質**:記了帳但沒有真的匯出去
 * —— 那幾筆的付款方式本來就是「無」。
 *
 * ★★ 代價要知道:換掉之後就**沒辦法只篩「房務的支出」**了。
 *   之後如果有別的來源也是非實支（折舊、內部分攤），
 *   它們會跟房務清潔混在同一個標籤底下分不開。
 *   真的需要時再加第二個標籤，不要把這一個改回去。
 *
 * ★ 換的時候資料庫裡**一筆都還沒產生**（09-03 查過 `hk_job_key` 是 0），
 *   所以沒有既有資料要改名。之後再改就要配一支 migration 了。
 */

/** 記了帳但沒有真的付錢出去。房務清潔與人事費目前都是這一種。 */
export const TAG_NON_CASH = '非實支';

/** PostgREST 的 `cs`（contains）要的格式:`{非實支}` */
export const TAG_NON_CASH_PG = `{${TAG_NON_CASH}}`;

/** 這一筆是不是非實支。★ `tags` 可能是 null。 */
export function isNonCash(tags: string[] | null | undefined): boolean {
  return (tags ?? []).includes(TAG_NON_CASH);
}
