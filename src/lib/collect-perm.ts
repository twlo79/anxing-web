/**
 * 誰可以按「收款」（純函式）。
 *
 * ============================================================
 * 【2026-09-02 使用者：「把管家與主管的權限關掉，不能去按收款，
 *   可以檢視，按了會有警示」】
 *
 * 三個地方的「收款」全部收成同一條規則:
 *
 *   契約收租     長租每期的租金
 *   短租訂單收款 訂單頁那顆
 *   押金收款     房客交的押金
 *
 * ★★★ 這是**推翻 migration_154 的一部分**。那一支當時把
 *   「契約與訂單編輯」全面開放給管家，含訂單收款。
 *   現在收回來的只有**收錢**這件事 —— 其餘（固定加費、收款證明照片、
 *   訂單編輯）一個字都不動。
 *
 * ============================================================
 * 【★★ 為什麼是「按了跳訊息」而不是把按鈕藏起來】（使用者選的）
 *
 * 藏起來的話，管家不知道這件事做得到，只會改用 LINE 問 ——
 * 而那通訊息沒有人記得回。
 *
 * 按鈕留著、點了說「只有會計能收款」，他就知道**要找誰**。
 *
 * ============================================================
 * 【★★★ 這一層只擋畫面】
 *
 * 真正擋住寫入的是 RLS 與觸發器。前端只是讓人不會誤按 ——
 * 匯入、API、之後新寫的程式都繞得過這裡
 * （CLAUDE.md:「RLS 擋下的 UPDATE 回成功且影響 0 列」）。
 */

/** 可以收款的角色。★ 只有這兩個 —— 錢進來的紀錄是會計的責任。 */
export const COLLECT_ROLES = ['accountant', 'super_admin'] as const;

export function canCollect(role: string | null | undefined): boolean {
  return (COLLECT_ROLES as readonly string[]).includes(role ?? '');
}

/**
 * 按了但沒權限時要說什麼。
 *
 * ★ 訊息要**說得出找誰**，不是只說「權限不足」——
 *   使用者看到「權限不足」只會再按一次，或者放棄。
 *
 * @param what 這一顆在收什麼（「這一期的租金」「押金」…）
 */
export function collectDeniedMsg(what = '款項'): string {
  return `只有會計能收款 —— ${what}請交給會計登記。你看得到紀錄，但不能代為收款。`;
}
