/**
 * 把一個需求項目手動拆成好幾個。
 *
 * ============================================================
 * 【為什麼需要】（2026-09-07 使用者:「研究可以手動拆開採購單」）
 *
 * 填單的人常把一整串東西打在同一個品名裡:
 *
 *     衛生紙*1箱 除霉劑*12瓶 洗衣精*2瓶
 *
 * 那一列在系統裡是**一個項目**，於是:
 *
 *   · 進度只算得出「1 項」，而實際上是三樣東西
 *   · 建請款單時三樣擠在同一列，金額只填得了一個總數
 *   · 買到一半沒辦法標「衛生紙買了、除霉劑還沒」
 *
 * ★★ 而且建立之後**完全沒有路可以改品名** —— 編輯視窗只給新增用,
 *   既有的單只改得動平台、到貨、採購日與狀態。
 *   在這之前唯一的辦法是整張單作廢重開,
 *   而那會把已經填好的採購資訊一起丟掉。
 *
 *
 * ============================================================
 * 【★★★ 為什麼不直接按空白切就算了】
 *
 * 按空白切對上面那個例子剛好對。但:
 *
 *     衛生紙 大包裝 *1箱      → 切成三項
 *     3M 魔布 *2入            → 切成三項
 *
 * 而切錯之後**沒有還原鍵** —— 三列已經各自有 id 了,
 * 要收回去得一列一列刪。
 *
 * 所以這裡只負責**猜一個起點**,人看過、改完、按確認才寫進去
 * （2026-09-07 使用者選「跳出可編輯的框，確認才寫」）。
 */

// ── 能不能拆 ──────────────────────────────────────

export type SplittableItem = {
  item_name: string;
  status: string;
  /** 被哪一列請款項目領走。有值就不能拆。 */
  request_item_id?: string | null;
  /** 領走它的那張請款單編號，只拿來寫錯誤訊息。 */
  request_no?: string | null;
};

/**
 * 這一項可不可以拆。**可以拆回 `null`，不能拆回一句話。**
 *
 * ★★★ 已經被請款單領走的一定要擋。
 *
 *   請款項目與需求項目是**一對一**（`purchase_demand_items.request_item_id`）。
 *   拆成三列之後，那張請款單只認得原本那一列 ——
 *   另外兩列會變成「沒有人在買、但狀態寫著已請款」的孤兒,
 *   而畫面上它們看起來完全正常。
 *
 *   ★ 這不會報錯。所以擋在按下去的那一刻，不是等資料歪掉再查。
 *
 * ★★ 已取消的不給拆 —— 拆出來的每一列都是已取消,沒有任何意義,
 *   只是讓清單變長。
 *
 * ★ 已採購（done）**可以拆**。使用者要拆的那一張就是已採購的 ——
 *   東西買回來了才發現當初三樣打成一列,那時候才想分開記。
 */
export function splitBlockedReason(i: SplittableItem): string | null {
  if (i.request_item_id) {
    return `這一項已經被請款單${i.request_no ? ` ${i.request_no}` : ''}領走了`
      + ' —— 要拆的話請先在請款單那邊退回這一項。';
  }
  if (i.status === 'requested') {
    return '這一項的狀態是已請款 —— 先改回待採購或已詢價再拆，'
      + '不然拆出來的幾列會是「沒有請款單卻寫著已請款」。';
  }
  if (i.status === 'cancelled') {
    return '這一項已經取消了，拆開沒有意義。';
  }
  return null;
}

// ── 拆 ────────────────────────────────────────────

/**
 * 一次最多拆幾列。
 *
 * ★ 不是技術限制,是**防手滑** —— 整份 Excel 貼進那個框的話,
 *   一按確認就是幾百列,而收回去要一列一列刪。
 *   真的要那麼多列的人會分兩次拆,那沒有損失。
 */
export const SPLIT_MAX = 30;

/**
 * 猜一個起點:按**空白**切開，一行一項。
 *
 * ★★ 全形空白也要切。填單的人在中文輸入法底下打的空白常常是全形,
 *   而那在畫面上跟半形長得一模一樣 —— 只切半形的話,
 *   使用者會看到「明明有空白卻沒拆開」而不知道為什麼。
 *
 * ★ 規格說明（spec）**不併進來**。它是另一個欄位,
 *   併進來的話拆完每一列的品名都拖著一段規格,
 *   而那段規格本來就會原樣留在每一列上。
 */
export function splitDraft(itemName: string): string {
  return (itemName ?? '')
    .split(/[\s　]+/)
    .map((s) => s.trim())
    .filter((s) => s.length > 0)
    .join('\n');
}

/**
 * 把框裡的文字讀成一列一項。
 *
 * ★ 逐行切,**行內的空白留著** —— 人在框裡自己排好的
 *   「衛生紙 大包裝 *1箱」就是他要的那一列,不可以再切一次。
 */
export function parseSplitLines(text: string): string[] {
  return (text ?? '')
    .split(/\r?\n/)
    .map((s) => s.trim())
    .filter((s) => s.length > 0);
}

export type SplitPlan = {
  /**
   * 留給**原本那一列**的新品名。
   *
   * ★★★ 第一列一定是 `update` 不是「刪掉重建」。
   *   重建的話那一列的 id 會變,而 id 一變:
   *     · 稽核紀錄接不起來（新的 id 沒有歷史）
   *     · 已經填好的平台、到貨日、採購日要重寫一次
   *     · 任何指著舊 id 的東西全部斷掉
   *   換一個品名就夠了,不需要換一列。
   */
  keep: string;
  /** 要新增的那幾列的品名。只有一行時是空陣列 —— 那次是改名不是拆。 */
  add: string[];
};

/**
 * 從框裡的內容算出要怎麼寫。**不能寫就回錯誤訊息。**
 *
 * ★ 只有一行是合法的 —— 那是「改名」。
 *   擋掉的話,人發現品名打錯字時又沒有路可以改了,
 *   而這個框已經是全站唯一能改品名的地方。
 */
export function planSplit(text: string): { plan: SplitPlan } | { error: string } {
  const lines = parseSplitLines(text);
  if (lines.length === 0) return { error: '至少要留一行 —— 空白的話這一項就沒有品名了。' };
  if (lines.length > SPLIT_MAX) {
    return { error: `一次最多 ${SPLIT_MAX} 列，現在有 ${lines.length} 列。分兩次拆。` };
  }
  return { plan: { keep: lines[0], add: lines.slice(1) } };
}

/**
 * 拆完之後，新增的那幾列要帶哪些欄位。
 *
 * ★★★ **除了品名，其他全部照抄。**
 *
 *   物業／用途、規格、建議連結、平台、到貨日、採購日、狀態 ——
 *   這些描述的是「這批東西」,拆開之後每一樣都還是那批的一部分。
 *
 *   ★★ 尤其是**狀態**。使用者要拆的那張是「已採購」,
 *     新增的兩列若回到「待採購」,那張單會從「全部採購完」
 *     變成「1 項待採購」—— 明明東西早就買回來了。
 *
 *   ★ `request_item_id` **不抄**（也抄不到 —— 有值的根本不給拆）。
 */
export function inheritedFields<T extends Record<string, unknown>>(
  src: T,
  keys: readonly (keyof T)[],
): Partial<T> {
  const out: Partial<T> = {};
  for (const k of keys) out[k] = src[k];
  return out;
}

