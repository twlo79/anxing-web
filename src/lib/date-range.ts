/**
 * 起訖日期／月份的連動規則。
 *
 * ============================================================
 * 【問題】（2026-08-27 使用者截圖：營收頁 `2026-08 ~ 2026-07`，總額 $0）
 *
 * 起訖是兩個各自獨立的輸入。使用者改了起日之後迄日還停在舊值，
 * 於是變成**起日晚於迄日** —— 那個區間查不到任何東西。
 *
 * ★★ 而畫面說的是「$0・0 筆認列」。
 *
 *   那句話**看起來完全合理** —— 「這個月還沒有營收」也長這樣。
 *   沒有紅字、沒有警告，使用者不會想到是自己的區間反了。
 *   跟 README 9.2 那條「空的但合理」是同一種毛病：
 *   系統回答得很有自信，而問題出在問題本身。
 *
 * 所以解法不是「查不到的時候提示他」，是**根本不讓那種區間存在**。
 *
 *
 * ============================================================
 * 【★★ 規則：補空的、擋倒置，但不要沒收使用者選好的東西】
 *
 * 直覺的寫法是「改起日 → 迄日一律跟著等於起日」。**那是錯的**：
 * 已經選好 1 月~12 月的人只是想把起點往前挪一個月，
 * 結果迄日被吃掉，他得再選一次 —— 而且不會知道是誰改的。
 *
 * 所以只在**這一頭的值讓區間變得不合理**時才動另一頭：
 *
 *   改起日  迄日是空的、或早於新的起日  → 迄日 ＝ 起日
 *           迄日還在起日之後（區間仍合理） → **不動**
 *
 *   改迄日  同理，反過來。
 *
 * ★ 清空（選成空字串）**不連動** —— 那是「我不要限制這一頭」，
 *   是明確的意圖，不是不小心。
 *
 *
 * ============================================================
 * 【為什麼用字串比大小】
 *
 * `<input type="date">` 給的是 `2026-08-27`、`type="month"` 給的是 `2026-08`。
 * 兩種都是**固定寬度、由大到小**的格式，字典序等於時間序。
 *
 * ★ 所以同一支函式吃得下日期與月份，不必分兩套 ——
 *   而分兩套的下場是其中一套之後沒有跟著改。
 *   （前提是兩邊格式一致，混用 `2026-08` 與 `2026-08-27` 才需要小心，
 *   而同一組起訖不可能一個是月一個是日。）
 */

export type Range = { from: string; to: string };

const norm = (v: string | null | undefined) => (v ?? '').trim();

/**
 * 使用者改了**起**那一頭之後，整組該變成什麼。
 *
 * @param from 使用者剛選的起日／起月
 * @param to   目前的迄日／迄月
 */
export function syncFrom(from: string | null | undefined, to: string | null | undefined): Range {
  const f = norm(from);
  const t = norm(to);
  // 清空起點 = 「不要限制這一頭」,是明確的意圖 —— 不要順手把迄點也動掉
  if (!f) return { from: '', to: t };
  // 迄點空的,或早於新的起點 → 補成同一天/同一個月
  return { from: f, to: !t || t < f ? f : t };
}

/** 使用者改了**迄**那一頭之後，整組該變成什麼。 */
export function syncTo(from: string | null | undefined, to: string | null | undefined): Range {
  const f = norm(from);
  const t = norm(to);
  if (!t) return { from: f, to: '' };
  return { from: !f || f > t ? t : f, to: t };
}

/**
 * 這一組區間現在是不是反的。
 *
 * ★ 連動之後照理不會出現，留著是為了**舊的網址**：
 *   有人把 `?from=2026-08&to=2026-07` 存成書籤，或別人貼給他，
 *   那條路沒有經過連動。畫面要看得出來，不能又是一句無辜的「$0」。
 */
export const isReversed = (from: string | null | undefined, to: string | null | undefined) => {
  const f = norm(from);
  const t = norm(to);
  return !!f && !!t && f > t;
};
