/**
 * 剛剛存好的那一筆，要怎麼讓人看得到。
 *
 * ============================================================
 * 【問題】（2026-08-22 使用者提出）
 *
 * 「可以在訂單輸入完先出現在第一列，或是有標記，比較好查看」
 *
 * 訂單頁存完之後只跳一句「已儲存」，然後 load() 重新載入 ——
 * 那一筆就**散進 `checkin desc` 的排序裡**了。
 *
 * 而這一頁是**伺服器端分頁**（一頁 50 筆）。所以:
 *
 *   · 補登一筆去年的訂單 → 它落在第 5 頁,畫面上完全看不到
 *   · 存完剛好被目前的篩選排除（例如篩「未付款」而你標了已付）→ 直接消失
 *
 * 兩種情況畫面都只說「已儲存」，而使用者看到的是**一筆都沒變的清單**。
 * 第一個反應一定是「沒存進去」，然後再存一次。
 *
 *
 * ============================================================
 * 【為什麼不直接改排序把它排到第一列】
 *
 * 最直覺的做法是把排序改成 `updated_at desc`。不行:
 *
 *   · 這一頁預設按**入住日**排，那是每天在用的順序 ——
 *     改掉之後所有人都要重新適應，只為了那一筆
 *   · 伺服器端分頁下，改排序等於整份清單重排,
 *     使用者原本看到哪裡也跟著跑掉
 *
 * 所以排序一個字都不動，改成**在清單最上面多畫一列**:
 * 那一列不屬於任何一頁，是「剛剛那筆」的獨立位置。
 * 它同時回答了「存進去了嗎」與「它去哪了」。
 *
 *
 * ============================================================
 * 【為什麼要會過期】
 *
 * 標記一直亮著的話，第二天打開這一頁還看得到「剛剛儲存」——
 * 那句話就變成謊話。而且置頂那一列會一直佔著位置。
 *
 * 45 秒:夠看清楚、夠捲過去點開，短到不會跨越「下一件事」。
 *
 * 【為什麼寫在 .ts 不是 .tsx】
 * 測試環境不處理 JSX，寫在元件裡的判斷式測不到。
 */

export type SavedMark = { id: string; at: number } | null;

/** 標記存活多久（毫秒）。見檔頭「為什麼要會過期」 */
export const SAVED_TTL_MS = 45_000;

export type SavedState =
  /** 沒有東西要標 */
  | 'none'
  /** 那一筆就在目前這頁的清單裡 —— 只要把它highlight起來 */
  | 'inline'
  /** 不在這頁（被分頁或篩選擋掉）—— 要在清單最上面另外畫一列 */
  | 'pinned';

/**
 * 剛存的那一筆現在該怎麼呈現。
 *
 * @param mark   存檔時記下的 { id, at }
 * @param rowIds 目前這一頁清單上的 id
 * @param now    現在時間（毫秒）。傳進來而不是在裡面呼叫 Date.now()，
 *               否則測不到過期
 */
export function savedState(
  mark: SavedMark, rowIds: readonly string[], now: number,
  ttlMs: number = SAVED_TTL_MS,
): SavedState {
  if (!mark) return 'none';
  /*
   * ★ 用 `>=` 不是 `>`。剛好等於 TTL 的那一毫秒算過期 ——
   *   邊界要選一邊,而「已經到期就收掉」比較好解釋。
   */
  if (now - mark.at >= ttlMs) return 'none';
  return rowIds.includes(mark.id) ? 'inline' : 'pinned';
}

/**
 * 置頂那一列要寫什麼理由。
 *
 * ★ **不猜具體原因。**
 *   篩選與分頁都在伺服器端做，前端手上沒有足夠的資訊分辨
 *   「它在第 5 頁」與「它被篩選排除了」——
 *   猜錯的話使用者會照著錯的提示去調篩選，然後更找不到。
 *
 *   所以只講**確定的事**:它存好了、它不在這一頁、可以怎麼找到它。
 */
export function pinnedHint(hasFilters: boolean): string {
  return hasFilters
    // 有篩選 → 最可能的兩個原因都提一次,但不指定是哪一個
    ? '已儲存。它不在目前的篩選或這一頁裡 —— 清掉篩選就找得到。'
    : '已儲存。依目前的排序，它不在這一頁。';
}

/**
 * 目前有沒有套用任何篩選。
 *
 * ★ 分開成一支是為了測得到 —— 這種「有沒有值」的判斷寫在 JSX 裡
 *   最容易漏掉其中一個欄位，而漏掉的症狀是提示句講錯話。
 */
export function hasAnyFilter(f: Record<string, unknown>): boolean {
  return Object.values(f).some((v) =>
    v !== null && v !== undefined && v !== '' && v !== 'all');
}
