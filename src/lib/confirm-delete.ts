/**
 * 「要打字才刪得掉」的那一段。
 *
 * ══════════════════════════════════════════════════════════
 * 【使用者 2026-09-18】
 *   「刪除 移到編輯裡面」
 *   「不要那麼容易被刪掉」
 *
 * ══════════════════════════════════════════════════════════
 * 【★★★ 為什麼原本的不夠】
 *
 * 原本是列上一顆「刪掉」，按下去跳 `confirm()` ——
 * 而瀏覽器的 confirm **按 Enter 就過了**。
 * 也就是說「點一下 ＋ 一個鍵」就刪掉一個救不回來的檔案。
 *
 * 現在是三道關:
 *   ① 要先進編輯視窗
 *   ② 要點那行紅字（底下才展開）
 *   ③ **要把標題打一次**
 *
 * ══════════════════════════════════════════════════════════
 * 【★★ 為什麼寫在 .ts】
 *
 * 「打成什麼才算對」是判斷式。寫在 `.tsx` 裡測不到（CLAUDE.md），
 * 而這一段判斷錯的後果是**刪掉一個救不回來的檔案**。
 *
 * ══════════════════════════════════════════════════════════
 * 【★ 比對規則：前後空白不算，其餘一個字都不能差】
 *
 * 只吃掉前後空白（複製貼上常常多一個）。
 * 大小寫、全形半形、中間的空白**都要一樣** ——
 * 放寬的話這道關就只是「隨便打幾個字」，等於沒有。
 */

/** 打的字算不算對。 */
export function deleteMatches(
  typed: string | null | undefined,
  target: string | null | undefined,
): boolean {
  const a = String(typed ?? '').trim();
  const b = String(target ?? '').trim();
  /*
   * ★★★ 目標是空的時候**一律不給刪**。
   *   空 === 空 會回 true —— 那樣沒打任何字就按得下去，
   *   而「標題是空的」那幾筆正是最該小心的（看不出是哪一筆）。
   */
  if (!b) return false;
  return a === b;
}

/**
 * 那顆「刪掉」按不下去的理由。`null` ＝ 按得下去。
 *
 * ★ 灰掉的按鈕要說得出為什麼（anxing-ui 二-6）——
 *   一顆灰掉而不解釋的鈕，使用者會以為系統壞了。
 */
export function whyDeleteBlocked(
  typed: string | null | undefined,
  target: string | null | undefined,
): string | null {
  const b = String(target ?? '').trim();
  if (!b) return '這一筆沒有標題，沒辦法用打字確認 —— 先去填一個標題';
  const a = String(typed ?? '').trim();
  if (!a) return '打對了才按得下去';
  return a === b ? null : '跟上面那一行不一樣';
}

/** 打對之後底下那句話。 */
export const DELETE_READY = '按下去就真的不見了';
