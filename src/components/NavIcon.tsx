/**
 * ============================================================
 * 【一個主色、一個輔色 —— 十四個顏色是錯的】
 *
 * 上一版每項一色（Apple 系統色盤）。單看側邊欄很漂亮，
 * 但那些顏色會滲進整個畫面：分頁、統計卡、表格的底色全部跟著各自上色，
 * 一張押金清單看起來像調色盤。**資料表最需要的是不搶戲的背景。**
 *
 * 收回兩個色：
 *   主色 #41689B  藍   —— 導覽、按鈕、選取狀態、可點的東西
 *   輔色 #3FAE7C  綠   —— 只有「錢進來」與「正常/完成」用
 *
 * 顏色一少，它就重新變成訊號：畫面上出現綠色時，那是有意義的，
 * 而不是「這一項剛好被分到綠色」。
 *
 * 圖示全部用中性的板岩灰藍，選取時才轉白 —— 分辨靠的是字形，不是顏色。
 * 字形已經為此重畫過（床有枕頭、帳簿有書背、營收有金額符號）。
 * ============================================================
 */
